"""
Numerical analysis of the 37-bus temporal-spatial SCL experiment.

This module keeps only analysis products that are consumed downstream or
provide a compact record of the retained temporal evidence. Publication
figures are generated by ``plot_temporal.py``.

Temporal normalization
----------------------
The intact temporal field is normalized to the independently solved temporal
reference state:

    delta_i_ref(t)
        = 100 * [SCL_i(t) - SCL_i,ref] / SCL_i,ref

where the reference state is the intact state at load_scale = 1.0 using the
same deterministic dispatch/commitment rule as the temporal sequence.

Expected inputs
---------------
scl_timeseries.csv
dispatch_schedule.csv
reference_scl.csv

Outputs (under results/glover37/temporal/analysis/)
---------------------------------------------------
commitment_state_by_hour.csv
intact_trajectories.csv
contingency_effect.csv
summary.csv

The raw run outputs remain the canonical data from which all aggregate
statistics can be recomputed.

Example
-------
python -m experiments.glover37.analyze_temporal \
    --input-dir results/glover37/temporal \
    --output-dir results/glover37/temporal/analysis
"""

from __future__ import annotations

import argparse
from itertools import combinations
from pathlib import Path

import numpy as np
import pandas as pd


REQUIRED = {
    "scl": "scl_timeseries.csv",
    "dispatch": "dispatch_schedule.csv",
    "reference": "reference_scl.csv",
}

CONTINGENCY_CASE = "line_39_47_out"


def parse_args():
    parser = argparse.ArgumentParser(
        description=(
            "Analyze temporal-spatial SCL variation "
            "in the Glover 37-bus experiment."
        )
    )
    parser.add_argument(
        "--input-dir",
        type=Path,
        default=Path("results/glover37/temporal/raw"),
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("results/glover37/temporal/analysis"),
    )
    return parser.parse_args()


def require_columns(df, cols, name):
    missing = [c for c in cols if c not in df.columns]
    if missing:
        raise ValueError(
            f"{name} missing required columns: {missing}"
        )


def parse_bool_series(series: pd.Series, name: str) -> pd.Series:
    values = (
        series.astype(str)
        .str.strip()
        .str.lower()
        .map(
            {
                "true": True,
                "false": False,
                "1": True,
                "0": False,
            }
        )
    )

    if values.isna().any():
        raise ValueError(
            f"Could not parse {name} as boolean."
        )

    return values.astype(bool)


def load_inputs(input_dir: Path):
    paths = {
        key: input_dir / filename
        for key, filename in REQUIRED.items()
    }

    missing = [
        str(path)
        for path in paths.values()
        if not path.exists()
    ]
    if missing:
        raise FileNotFoundError(
            "Missing required files:\n  "
            + "\n  ".join(missing)
        )

    scl = pd.read_csv(paths["scl"])
    dispatch = pd.read_csv(paths["dispatch"])
    reference = pd.read_csv(paths["reference"])

    require_columns(
        scl,
        [
            "hour_index",
            "timestamp",
            "case",
            "bus",
            "SCL_MVA",
        ],
        "scl_timeseries.csv",
    )
    require_columns(
        dispatch,
        [
            "hour_index",
            "timestamp",
            "generator",
            "bus",
            "committed",
            "dispatch_MW",
        ],
        "dispatch_schedule.csv",
    )
    require_columns(
        reference,
        [
            "bus",
            "SCL_MVA",
            "load_scale",
        ],
        "reference_scl.csv",
    )

    for df in (scl, dispatch):
        df["timestamp"] = pd.to_datetime(
            df["timestamp"]
        )

    for df in (scl, dispatch, reference):
        df["bus"] = pd.to_numeric(
            df["bus"],
            errors="raise",
        ).astype(int)

    scl["hour_index"] = pd.to_numeric(
        scl["hour_index"],
        errors="raise",
    ).astype(int)
    dispatch["hour_index"] = pd.to_numeric(
        dispatch["hour_index"],
        errors="raise",
    ).astype(int)

    dispatch["committed"] = parse_bool_series(
        dispatch["committed"],
        "dispatch_schedule.csv:committed",
    )

    if reference["bus"].duplicated().any():
        duplicated = sorted(
            reference.loc[
                reference["bus"].duplicated(keep=False),
                "bus",
            ]
            .unique()
            .tolist()
        )
        raise ValueError(
            "reference_scl.csv contains duplicate buses: "
            f"{duplicated}"
        )

    if not np.allclose(
        reference["load_scale"].to_numpy(dtype=float),
        1.0,
    ):
        raise ValueError(
            "reference_scl.csv is expected to contain "
            "the temporal reference state at load_scale = 1.0."
        )

    return scl, dispatch, reference


def commitment_context(
    dispatch: pd.DataFrame,
) -> pd.DataFrame:
    rows = []

    for h, group in dispatch.groupby(
        "hour_index",
        sort=True,
    ):
        committed = group[
            group["committed"]
        ].copy()
        offline = group[
            ~group["committed"]
        ].copy()

        rows.append(
            {
                "hour_index": int(h),
                "n_committed": int(len(committed)),
                "committed_buses": ";".join(
                    map(
                        str,
                        committed["bus"]
                        .astype(int)
                        .tolist(),
                    )
                ),
                "offline_buses": ";".join(
                    map(
                        str,
                        offline["bus"]
                        .astype(int)
                        .tolist(),
                    )
                ),
                "offline_generators": ";".join(
                    offline["generator"]
                    .astype(str)
                    .tolist()
                ),
                "total_dispatch_MW": float(
                    group["dispatch_MW"].sum()
                ),
            }
        )

    ctx = pd.DataFrame(rows)

    ctx["commitment_changed"] = (
        ctx["offline_generators"].fillna("")
        != ctx["offline_generators"]
        .shift()
        .fillna("")
    )

    if not ctx.empty:
        ctx.loc[
            ctx.index[0],
            "commitment_changed",
        ] = False

    return ctx


def build_intact(
    scl: pd.DataFrame,
    reference: pd.DataFrame,
) -> pd.DataFrame:
    intact = scl[
        scl["case"].str.lower() == "intact"
    ].copy()

    if intact.empty:
        raise ValueError(
            "No intact case found in scl_timeseries.csv"
        )

    intact = (
        intact.sort_values(
            ["bus", "hour_index"]
        )
        .reset_index(drop=True)
    )

    ref = (
        reference[
            ["bus", "SCL_MVA"]
        ]
        .rename(
            columns={
                "SCL_MVA": "SCL_reference_MVA"
            }
        )
    )

    intact = intact.merge(
        ref,
        on="bus",
        how="left",
        validate="many_to_one",
    )

    if intact["SCL_reference_MVA"].isna().any():
        missing = sorted(
            intact.loc[
                intact["SCL_reference_MVA"].isna(),
                "bus",
            ]
            .unique()
            .tolist()
        )
        raise ValueError(
            "Reference SCL is missing for buses: "
            f"{missing}"
        )

    intact[
        "SCL_deviation_from_reference_pct"
    ] = (
        100.0
        * (
            intact["SCL_MVA"]
            - intact["SCL_reference_MVA"]
        )
        / intact["SCL_reference_MVA"]
    )

    return intact


def count_pairwise_order_reversals(
    intact: pd.DataFrame,
) -> int:
    wide = (
        intact.pivot(
            index="hour_index",
            columns="bus",
            values="SCL_MVA",
        )
        .sort_index()
    )

    pairs_with_reversal = 0

    for a, b in combinations(
        wide.columns,
        2,
    ):
        difference = (
            wide[a] - wide[b]
        ).to_numpy(float)

        signs = np.sign(difference)
        nonzero = signs[signs != 0]

        if (
            len(nonzero) > 1
            and np.any(
                nonzero[1:]
                != nonzero[:-1]
            )
        ):
            pairs_with_reversal += 1

    return pairs_with_reversal



def build_contingency_effect(
    scl: pd.DataFrame,
) -> pd.DataFrame:
    """Derive paired intact-versus-contingency SCL changes from solved states."""
    keys = ["hour_index", "timestamp", "bus"]

    intact = (
        scl.loc[
            scl["case"].str.lower() == "intact",
            keys + ["SCL_MVA"],
        ]
        .rename(columns={"SCL_MVA": "SCL_intact_MVA"})
    )

    contingency = (
        scl.loc[
            scl["case"].str.lower() == CONTINGENCY_CASE,
            keys + ["SCL_MVA"],
        ]
        .rename(columns={"SCL_MVA": "SCL_contingency_MVA"})
    )

    if intact.empty:
        raise ValueError("No intact states found in scl_timeseries.csv.")
    if contingency.empty:
        raise ValueError(
            f"No '{CONTINGENCY_CASE}' states found in scl_timeseries.csv."
        )

    out = intact.merge(
        contingency,
        on=keys,
        how="inner",
        validate="one_to_one",
    )

    if len(out) != len(intact) or len(contingency) != len(intact):
        raise ValueError(
            "Intact and contingency temporal states are not fully paired."
        )

    out["delta_SCL_MVA"] = (
        out["SCL_contingency_MVA"] - out["SCL_intact_MVA"]
    )
    out["delta_SCL_pct"] = (
        100.0 * out["delta_SCL_MVA"] / out["SCL_intact_MVA"]
    )

    return out.sort_values(keys).reset_index(drop=True)

def temporal_summary(
    intact: pd.DataFrame,
    cont: pd.DataFrame,
    ctx: pd.DataFrame,
) -> pd.DataFrame:
    n_buses = int(
        intact["bus"].nunique()
    )

    ranks = intact[
        [
            "hour_index",
            "bus",
            "SCL_MVA",
        ]
    ].copy()

    ranks["SCL_rank"] = (
        ranks.groupby(
            "hour_index"
        )["SCL_MVA"]
        .rank(
            method="min",
            ascending=False,
        )
    )

    rank_span = (
        ranks.groupby("bus")["SCL_rank"]
        .agg(["min", "max"])
    )
    buses_with_rank_changes = int(
        (rank_span["max"] > rank_span["min"]).sum()
    )

    pairwise_reversals = (
        count_pairwise_order_reversals(
            intact
        )
    )

    intact_critical_hours = (
        intact.loc[
            intact.groupby("bus")[
                "SCL_MVA"
            ].idxmin(),
            ["bus", "hour_index"],
        ]
        .set_index("bus")["hour_index"]
    )

    contingency_critical_hours = (
        cont.loc[
            cont.groupby("bus")[
                "SCL_contingency_MVA"
            ].idxmin(),
            ["bus", "hour_index"],
        ]
        .set_index("bus")["hour_index"]
    )

    common_buses = (
        intact_critical_hours.index
        .intersection(
            contingency_critical_hours.index
        )
    )

    buses_with_changed_minimum_state = int(
        (
            intact_critical_hours.loc[common_buses]
            != contingency_critical_hours.loc[common_buses]
        ).sum()
    )

    return pd.DataFrame(
        [
            {
                "n_buses": n_buses,
                "n_hours": int(
                    intact["hour_index"].nunique()
                ),
                "n_commitment_states": int(
                    ctx["offline_generators"].nunique()
                ),
                "n_commitment_transitions": int(
                    ctx["commitment_changed"].sum()
                ),
                "n_distinct_intact_minimum_hours": int(
                    intact_critical_hours.nunique()
                ),
                "buses_with_rank_changes": (
                    buses_with_rank_changes
                ),
                "bus_pairs_with_ordering_reversals": (
                    pairwise_reversals
                ),
                "buses_with_changed_minimum_state_under_contingency": (
                    buses_with_changed_minimum_state
                ),
            }
        ]
    )


def main():
    args = parse_args()

    args.output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    (
        scl,
        dispatch,
        reference,
    ) = load_inputs(
        args.input_dir
    )

    ctx = commitment_context(
        dispatch
    )

    intact = build_intact(
        scl,
        reference,
    )

    cont = build_contingency_effect(
        scl
    )

    summary = temporal_summary(
        intact,
        cont,
        ctx,
    )

    ctx.to_csv(
        args.output_dir
        / "commitment_state_by_hour.csv",
        index=False,
    )

    intact.to_csv(
        args.output_dir
        / "intact_trajectories.csv",
        index=False,
    )

    cont.to_csv(
        args.output_dir
        / "contingency_effect.csv",
        index=False,
    )

    summary.to_csv(
        args.output_dir
        / "summary.csv",
        index=False,
    )

    row = summary.iloc[0]

    print(
        "Temporal-spatial SCL analysis complete."
    )
    print(
        f"Output directory: "
        f"{args.output_dir.resolve()}"
    )
    print(
        "Reference normalization: "
        "independent temporal state at load_scale = 1.0"
    )
    print(
        "Commitment states / transitions: "
        f"{int(row['n_commitment_states'])} / "
        f"{int(row['n_commitment_transitions'])}"
    )
    print(
        "Buses with intact rank changes: "
        f"{int(row['buses_with_rank_changes'])}/"
        f"{int(row['n_buses'])}"
    )
    print(
        "Bus pairs with ordering reversals: "
        f"{int(row['bus_pairs_with_ordering_reversals'])}"
    )
    print(
        "Buses whose minimum-SCL state changes "
        "under contingency: "
        f"{int(row['buses_with_changed_minimum_state_under_contingency'])}/"
        f"{int(row['n_buses'])}"
    )


if __name__ == "__main__":
    main()
